// Builds results/gate-summary.md mechanically from results/gate-results.csv and results/timing.json.
// The verdict logic implements docs/gate-rules.md section 3 and docs/speed-thresholds.md, nothing else.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

interface Row { run: string; edit_id: string; file: string; type: string; rule: string; pass: boolean; detail: string }

function parseCsv(text: string): Row[] {
  const out: Row[] = [];
  const lines = text.split('\n').filter(Boolean).slice(1);
  for (const line of lines) {
    const cells: string[] = [];
    let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i]!;
      if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; }
      else if (c === '"') inQ = true;
      else if (c === ',') { cells.push(cur); cur = ''; }
      else cur += c;
    }
    cells.push(cur);
    out.push({ run: cells[0]!, edit_id: cells[1]!, file: cells[2]!, type: cells[3]!, rule: cells[4]!, pass: cells[5] === 'true', detail: cells[6] ?? '' });
  }
  return out;
}

export const SPEED = { previewMs: 100, applyMs: 10, gzipBytes: 102400, rawBytes: 358400, scale10: { previewMs: 250, applyMs: 50 } };

interface Timing {
  bundle: { rawBytes: number; gzipBytes: number };
  perFile: { file: string; previewMs: { median: number }; applyMs: { median: number } }[];
  largestFixture: { file: string; bytes: number };
  scaling: Record<string, { previewMedianMs: number; applyMedianMs: number; applyStatus: string; bytes: number; elements: number }>;
}

export function writeSummary(_latest: string): void {
  const rows = parseCsv(readFileSync(join(ROOT, 'results/gate-results.csv'), 'utf8'));
  const timing = JSON.parse(readFileSync(join(ROOT, 'results/timing.json'), 'utf8')) as Timing;
  const runs = [...new Set(rows.map((r) => r.run))];
  const md: string[] = ['# Engine gate results', '', 'Generated by `harness/summary.ts` from `results/gate-results.csv` and `results/timing.json`. Do not edit by hand.', ''];

  // speed (same for every run: one build)
  const worstPrev = Math.max(...timing.perFile.map((r) => r.previewMs.median));
  const worstApply = Math.max(...timing.perFile.map((r) => r.applyMs.median));
  const s10 = timing.scaling['10x']!, s100 = timing.scaling['100x']!;
  const speed: { name: string; value: string; threshold: string; pass: boolean | null }[] = [
    { name: 'preview ready, worst per-file median', value: `${worstPrev.toFixed(1)} ms`, threshold: `<= ${SPEED.previewMs} ms`, pass: worstPrev <= SPEED.previewMs },
    { name: 'apply + export, worst per-file median', value: `${worstApply.toFixed(3)} ms`, threshold: `<= ${SPEED.applyMs} ms`, pass: worstApply <= SPEED.applyMs },
    { name: 'bundle gzip', value: `${timing.bundle.gzipBytes} B`, threshold: `<= ${SPEED.gzipBytes} B`, pass: timing.bundle.gzipBytes <= SPEED.gzipBytes },
    { name: 'bundle raw', value: `${timing.bundle.rawBytes} B`, threshold: `<= ${SPEED.rawBytes} B`, pass: timing.bundle.rawBytes <= SPEED.rawBytes },
    { name: '10x large-page preview ready, median', value: `${s10.previewMedianMs.toFixed(1)} ms`, threshold: `<= ${SPEED.scale10.previewMs} ms`, pass: s10.previewMedianMs <= SPEED.scale10.previewMs },
    { name: '10x large-page apply + export, median', value: `${s10.applyMedianMs.toFixed(3)} ms${s10.applyStatus === 'ok' ? '' : ' (' + s10.applyStatus + ')'}`, threshold: `<= ${SPEED.scale10.applyMs} ms`, pass: s10.applyMedianMs <= SPEED.scale10.applyMs && s10.applyStatus === 'ok' },
    { name: '100x large-page preview ready, median', value: `${s100.previewMedianMs.toFixed(1)} ms`, threshold: 'report only', pass: null },
    { name: '100x large-page apply + export, median', value: `${s100.applyMedianMs.toFixed(3)} ms`, threshold: 'report only', pass: null },
    { name: 'largest fixture', value: `${timing.largestFixture.file}, ${timing.largestFixture.bytes} B`, threshold: 'report only', pass: null },
  ];
  const speedOk = speed.every((s) => s.pass !== false);

  const verdicts: string[] = [];
  for (const run of runs) {
    const rr = rows.filter((r) => r.run === run);
    const edits = [...new Set(rr.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id))];
    const editPass = new Map(edits.map((id) => [id, rr.filter((r) => r.edit_id === id).every((r) => r.pass)]));
    const editInfo = new Map(edits.map((id) => { const r = rr.find((x) => x.edit_id === id)!; return [id, r] as const; }));
    const types = ['T1', 'T2', 'T3', 'T4'];
    const typeCount = types.map((t) => {
      const ids = edits.filter((id) => editInfo.get(id)!.type === t);
      return { t, pass: ids.filter((id) => editPass.get(id)).length, of: ids.length };
    });
    const total = edits.filter((id) => editPass.get(id)).length;
    const files = [...new Set(rr.map((r) => r.file))];
    const rt = rr.filter((r) => r.type === 'ROUNDTRIP');
    const rtOk = files.filter((f) => rt.filter((r) => r.file === f).length >= 2 && rt.filter((r) => r.file === f).every((r) => r.pass));
    const rules = ['E1', 'E2', 'E3', 'E4', 'E5'].map((rule) => {
      const x = rr.filter((r) => r.type !== 'ROUNDTRIP' && r.rule === rule);
      return { rule, pass: x.filter((r) => r.pass).length, of: x.length };
    });
    const refusals = rr.filter((r) => r.rule === 'E2' && r.detail.startsWith('refused'));

    md.push(`## Run ${run}`, '');
    md.push('### Per edit type', '', '| type | passed | of | line | met |', '|---|---|---|---|---|');
    for (const c of typeCount) md.push(`| ${c.t} | ${c.pass} | ${c.of} | >= 9 | ${c.pass >= 9 ? 'yes' : '**NO**'} |`);
    md.push(`| total | ${total} | ${edits.length} | >= 36 | ${total >= 36 ? 'yes' : '**NO**'} |`, '');
    md.push('### Per rule (edits passing the rule)', '', '| rule | passed | of |', '|---|---|---|');
    for (const r of rules) md.push(`| ${r.rule} | ${r.pass} | ${r.of} |`);
    md.push('', '### Per file', '', '| file | edits passed | of | no-op round trip |', '|---|---|---|---|');
    for (const f of files) {
      const ids = edits.filter((id) => editInfo.get(id)!.file === f);
      md.push(`| ${f} | ${ids.filter((id) => editPass.get(id)).length} | ${ids.length} | ${rtOk.includes(f) ? 'byte-identical, loads' : '**FAIL**'} |`);
    }
    const failed = edits.filter((id) => !editPass.get(id));
    md.push('', `### Failed edits (${failed.length})`, '');
    if (!failed.length) md.push('None.');
    for (const id of failed) {
      const info = editInfo.get(id)!;
      const bad = rr.filter((r) => r.edit_id === id && !r.pass);
      md.push(`- **${id}** ${info.file} ${info.type}: ${bad.map((b) => `${b.rule} (${b.detail})`).join('; ')}`);
    }
    md.push('', `Refusals detected: ${refusals.length}${refusals.length ? ' (' + refusals.map((r) => r.edit_id).join(', ') + ')' : ''}.`, '');
    const roundTripOk = rtOk.length === files.filter((f) => rt.some((r) => r.file === f)).length && rt.length > 0;
    const missed: string[] = [];
    for (const c of typeCount) if (c.pass < 9) missed.push(`${c.t} ${c.pass}/${c.of} (line 9/10)`);
    if (total < 36) missed.push(`total ${total}/${edits.length} (line 36/40)`);
    if (!roundTripOk) missed.push(`no-op round trip / load: ${rtOk.length}/${files.length} files ok`);
    for (const s of speed) if (s.pass === false) missed.push(`${s.name} ${s.value} (threshold ${s.threshold})`);
    let verdict: string;
    if (missed.length === 0) verdict = 'PASS';
    else {
      const t4Only = typeCount.filter((c) => c.t !== 'T4').every((c) => c.pass >= 9) && typeCount.find((c) => c.t === 'T4')!.pass < 9 && roundTripOk && speedOk;
      verdict = t4Only ? 'PASS WITH CHANGE (only T4 offset moves missed; the total line is counted as missed only through T4)' : 'FAIL';
    }
    md.push(`### Verdict, run ${run}: **${verdict}**`, '');
    if (missed.length) { md.push('Missed:', ...missed.map((m) => `- ${m}`), ''); }
    verdicts.push(`run ${run}: ${verdict}`);
  }
  md.push('## Speed (one build, `results/timing.json`)', '', '| metric | measured | threshold | met |', '|---|---|---|---|');
  for (const s of speed) md.push(`| ${s.name} | ${s.value} | ${s.threshold} | ${s.pass === null ? 'n/a' : s.pass ? 'yes' : '**NO**'} |`);
  md.push('', `Verdicts: ${verdicts.join('; ')}`, '');
  writeFileSync(join(ROOT, 'results/gate-summary.md'), md.join('\n'));
}
