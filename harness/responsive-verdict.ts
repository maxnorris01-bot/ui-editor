// Computes the responsive iteration verdict ONLY from the pass line in docs/responsive-rules.md section 4,
// reading the result files the harnesses wrote. Writes responsive-check/results/responsive-summary.md.
//   GATE_RUN=<n> npx tsx harness/responsive-verdict.ts       (n = the responsive run; regression runs are labelled "resp")
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

const RUN = process.env.GATE_RUN ?? '1';
function csv(path: string): Record<string, string>[] {
  const lines = readFileSync(path, 'utf8').split('\n').filter(Boolean);
  const head = lines[0]!.split(',');
  return lines.slice(1).map((line) => {
    const cells: string[] = []; let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) { const c = line[i]!; if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; } else if (c === '"') inQ = true; else if (c === ',') { cells.push(cur); cur = ''; } else cur += c; }
    cells.push(cur);
    return Object.fromEntries(head.map((h, i) => [h, cells[i] ?? '']));
  });
}
const resp = csv(join(ROOT, 'responsive-check/results/responsive-results.csv')).filter((r) => r.run === RUN);
const gate = csv(join(ROOT, 'results/gate-results.csv')).filter((r) => r.run === 'resp');
const real = csv(join(ROOT, 'realpage-check/results/realpage-results.csv')).filter((r) => r.run === 'resp');
const regress = JSON.parse(readFileSync(join(ROOT, 'responsive-check/results/regression.json'), 'utf8')) as { noMediaRule: number; byteIdentical: number; notIdentical: string[] };
const timing = JSON.parse(readFileSync(join(ROOT, 'results/timing.json'), 'utf8')) as { bundle: { rawBytes: number; gzipBytes: number }; overall: { worstMedian_previewMs: number; worstMedian_applyMs: number }; scaling: Record<string, { previewMedianMs: number; applyMedianMs: number }> };

const outcome = (rows: Record<string, string>[], id: string, idKey = 'id') => rows.find((r) => r[idKey] === id)?.outcome ?? 'FAIL';
const ids = (rows: Record<string, string>[], idKey: string, pat: RegExp) => [...new Set(rows.filter((r) => pat.test(r[idKey]!) && r.kind !== 'roundtrip').map((r) => r[idKey]!))];

const md: string[] = [`# Responsive iteration results, run ${RUN}`, '', 'Generated by `harness/responsive-verdict.ts` from the result files. Do not edit by hand. The truth of each REFUSED reason is checked separately by reading the file (session note).', ''];
const missed: string[] = [];

// 1. R01, R09
const item1 = ['R01', 'R09'].map((id) => ({ id, outcome: outcome(resp, id), why: resp.filter((r) => r.id === id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500) }));
const ok1 = item1.every((x) => x.outcome === 'PASS');
if (!ok1) missed.push(`1. R01/R09 at all test widths: ${item1.map((x) => `${x.id} ${x.outcome}`).join(', ')} (line: both PASS)`);

// 2. the 20 new specs
const s = ids(resp, 'id', /^S\d+$/);
const sOut = s.map((id) => ({ id, o: outcome(resp, id) }));
const pass2 = sOut.filter((x) => x.o === 'PASS').length;
const fail2 = sOut.filter((x) => x.o === 'FAIL').length;
const ok2 = s.length === 20 && pass2 >= 18 && fail2 === 0;
if (!ok2) missed.push(`2. responsive specs: ${pass2} PASS, ${fail2} FAIL of ${s.length} (line: >= 18 PASS, 0 FAIL)`);

// 3. regression
const gateIds = [...new Set(gate.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id))];
const gatePass = gateIds.filter((id) => gate.filter((r) => r.edit_id === id).every((r) => r.pass === 'true')).length;
const realIds = [...new Set(real.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id))].filter((id) => id !== 'R01' && id !== 'R09');
const realPass = realIds.filter((id) => real.filter((r) => r.edit_id === id).every((r) => r.pass === 'true')).length;
const ok3 = gatePass === 40 && realPass === 18 && regress.byteIdentical === regress.noMediaRule && regress.notIdentical.length === 0;
if (!ok3) missed.push(`3. regression: gate ${gatePass}/40, other real-page ${realPass}/18, byte-identical ${regress.byteIdentical}/${regress.noMediaRule}`);

// 4. no-op round trips
const rt = (rows: Record<string, string>[], key: string) => rows.filter((r) => r[key] === 'ROUNDTRIP' && r.rule === 'RT');
const rtGate = rt(gate, 'type'), rtReal = rt(real, 'type'), rtResp = resp.filter((r) => r.kind === 'roundtrip' && r.rule === 'RT');
const rtAll = [...rtGate, ...rtReal, ...rtResp];
const ok4 = rtAll.length > 0 && rtAll.every((r) => r.pass === 'true');
if (!ok4) missed.push(`4. no-op round trips: ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical`);

// 5. speed (docs/speed-thresholds.md)
const sp = [
  { n: 'preview ready, worst per-file median', v: timing.overall.worstMedian_previewMs, t: 100, u: 'ms' },
  { n: 'apply + export, worst per-file median', v: timing.overall.worstMedian_applyMs, t: 10, u: 'ms' },
  { n: 'bundle gzip', v: timing.bundle.gzipBytes, t: 102400, u: 'B' },
  { n: 'bundle raw', v: timing.bundle.rawBytes, t: 358400, u: 'B' },
  { n: '10x large page preview ready', v: timing.scaling['10x']!.previewMedianMs, t: 250, u: 'ms' },
  { n: '10x large page apply + export', v: timing.scaling['10x']!.applyMedianMs, t: 50, u: 'ms' },
];
const ok5 = sp.every((x) => x.v <= x.t);
if (!ok5) missed.push(`5. speed: ${sp.filter((x) => x.v > x.t).map((x) => `${x.n} ${x.v}${x.u} > ${x.t}${x.u}`).join('; ')}`);

md.push('## Pass line', '', '| item | measured | line | met |', '|---|---|---|---|');
md.push(`| 1. R01 and R09 at all test widths | ${item1.map((x) => `${x.id} ${x.outcome}`).join(', ')} | both PASS | ${ok1 ? 'yes' : '**NO**'} |`);
md.push(`| 2. new specs | ${pass2} PASS, ${sOut.filter((x) => x.o === 'REFUSED').length} REFUSED, ${fail2} FAIL of ${s.length} | >= 18 PASS and 0 FAIL | ${ok2 ? 'yes' : '**NO**'} |`);
md.push(`| 3. regression | gate ${gatePass}/40, other real-page ${realPass}/18, byte-identical ${regress.byteIdentical}/${regress.noMediaRule} | all | ${ok3 ? 'yes' : '**NO**'} |`);
md.push(`| 4. no-op round trips | ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical (${rtGate.length} gate, ${rtReal.length} real, ${rtResp.length} new) | all | ${ok4 ? 'yes' : '**NO**'} |`);
md.push(`| 5. speed thresholds | see below | all met | ${ok5 ? 'yes' : '**NO**'} |`, '');
md.push('### Speed', '', '| metric | measured | threshold | met |', '|---|---|---|---|');
for (const x of sp) md.push(`| ${x.n} | ${+x.v.toFixed(3)} ${x.u} | <= ${x.t} ${x.u} | ${x.v <= x.t ? 'yes' : '**NO**'} |`);
md.push('', '## Specs (outcome, diff size, notes)', '', '| id | case | fixture | outcome | diff | not-scaled notes |', '|---|---|---|---|---|---|');
for (const id of [...s, 'R01', 'R09']) {
  const r = resp.filter((x) => x.id === id);
  const e5 = r.find((x) => x.rule === 'E5')?.detail ?? '';
  const notes = JSON.parse(r.find((x) => x.rule === 'NOTES')?.detail || '[]') as unknown[];
  const first = r[0]!;
  md.push(`| ${id} | ${first.case} | ${first.fixture} | ${first.outcome} | ${first.outcome === 'REFUSED' ? '-' : e5.split(' | ')[0]} | ${notes.length} |`);
}
md.push('', '## Failures', '');
for (const x of [...sOut.filter((y) => y.o === 'FAIL').map((y) => ({ id: y.id, why: resp.filter((r) => r.id === y.id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500) })), ...item1.filter((y) => y.outcome !== 'PASS').map((y) => ({ id: y.id, why: y.why }))]) md.push(`- **${x.id}**: ${x.why}`);
md.push('', '## Refusals', '');
for (const x of sOut.filter((y) => y.o === 'REFUSED')) md.push(`- **${x.id}**: ${resp.find((r) => r.id === x.id && r.rule === 'E2')?.detail}`);
md.push('', `## Verdict, run ${RUN}: **${missed.length === 0 ? 'PASS' : 'FAIL'}**`, '');
for (const m of missed) md.push(`- ${m}`);
md.push('');
writeFileSync(join(ROOT, 'responsive-check/results/responsive-summary.md'), md.join('\n'));
console.log(md.join('\n'));
