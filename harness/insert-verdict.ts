// Computes the insert-and-comments verdict ONLY from the pass line in docs/insert-comments-rules.md section 5 (with amendment 1).
// Writes insert-check/results/insert-summary.md.
//   GATE_RUN=<id> npx tsx harness/insert-verdict.ts
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

const RUN = process.env.GATE_RUN ?? 'i1';
function csv(path: string): Record<string, string>[] {
  const lines = readFileSync(path, 'utf8').split('\n').filter(Boolean);
  const head = lines[0]!.split(',');
  return lines.slice(1).map((line) => {
    const cells: string[] = []; let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) { const c = line[i]!; if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; } else if (c === '"') inQ = true; else if (c === ',') { cells.push(cur); cur = ''; } else cur += c; }
    cells.push(cur);
    return Object.fromEntries(head.map((h, i) => [h, cells[i] ?? '']));
  });
}
const sh = (cmd: string): { ok: boolean; out: string } => { try { return { ok: true, out: execSync(cmd, { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] }).toString() }; } catch (e) { return { ok: false, out: String((e as { stdout?: Buffer }).stdout ?? e) }; } };

const ins = csv(join(ROOT, 'insert-check/results/insert-results.csv')).filter((r) => r.run === RUN);
const size = csv(join(ROOT, 'size-check/results/size-results.csv')).filter((r) => r.run === RUN);
const flex = csv(join(ROOT, 'size-check/results/size-flex-results.csv')).filter((r) => r.run === RUN);
const resp = csv(join(ROOT, 'responsive-check/results/responsive-results.csv')).filter((r) => r.run === RUN);
const gate = csv(join(ROOT, 'results/gate-results.csv')).filter((r) => r.run === RUN);
const real = csv(join(ROOT, 'realpage-check/results/realpage-results.csv')).filter((r) => r.run === RUN);
const regress = JSON.parse(readFileSync(join(ROOT, 'insert-check/results/regression.json'), 'utf8')) as { baselineFiles: number; byteIdentical: number; different: string[]; missing: string[]; extra: string[] };
const timing = JSON.parse(readFileSync(join(ROOT, 'results/timing.json'), 'utf8')) as { bundle: { rawBytes: number; gzipBytes: number }; overall: { worstMedian_previewMs: number; worstMedian_applyMs: number }; scaling: Record<string, { previewMedianMs: number; applyMedianMs: number }> };
const scorer = readFileSync(join(ROOT, 'insert-check/results/scorer-check.txt'), 'utf8');

const outcome = (rows: Record<string, string>[], id: string) => rows.find((r) => r.id === id)?.outcome ?? 'FAIL';
const idsOf = (rows: Record<string, string>[], key: string, pat: RegExp) => [...new Set(rows.filter((r) => pat.test(r[key] ?? '') && r.kind !== 'roundtrip').map((r) => r[key] ?? ''))];
const missed: string[] = [];
const md: string[] = [`# Insert and comments engine, results of run ${RUN}`, '', 'Generated by `harness/insert-verdict.ts` from the result files. Do not edit by hand. The truth of each REFUSED reason is checked separately: `harness/validate-insert-specs.ts` reads the fixtures without the engine, and the session note quotes the reasons.', ''];

// 1. the 36 specs
const ids = [...new Set(ins.filter((r) => /^I\d+$/.test(r.id ?? '')).map((r) => r.id!))];
const outs = ids.map((id) => ({ id, o: outcome(ins, id), fixture: ins.find((r) => r.id === id)!.fixture }));
const nPass = outs.filter((x) => x.o === 'PASS').length, nRef = outs.filter((x) => x.o === 'REFUSED').length, nFail = outs.filter((x) => x.o === 'FAIL').length;
const ok1 = ids.length === 36 && nFail === 0;
if (!ok1) missed.push(`1. I-specs: ${nPass} PASS, ${nRef} REFUSED as declared, ${nFail} FAIL of ${ids.length} (line: 36 specs, 0 FAIL)`);

// 2. regression
const gateIds = [...new Set(gate.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const allPass = (rows: Record<string, string>[], key: string, id: string) => rows.filter((r) => r[key] === id && ['E1', 'E2', 'E3', 'E4', 'E5'].includes(r.rule ?? '')).every((r) => r.pass === 'true');
const gatePass = gateIds.filter((id) => allPass(gate, 'edit_id', id)).length;
const realIds = [...new Set(real.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const realPass = realIds.filter((id) => allPass(real, 'edit_id', id)).length;
const sIds = idsOf(resp, 'id', /^S\d+$/);
const sOut = sIds.map((id) => outcome(resp, id));
const sPass = sOut.filter((o) => o === 'PASS').length, sRef = sOut.filter((o) => o === 'REFUSED').length, sFail = sOut.filter((o) => o === 'FAIL').length;
const zs = idsOf(size, 'id', /^Z\d+$/), fz = idsOf(flex, 'id', /^Z\d+$/);
const zPass = zs.filter((id) => outcome(size, id) === 'PASS').length;
const fPass = fz.filter((id) => outcome(flex, id) === 'PASS').length, fRef = fz.filter((id) => outcome(flex, id) === 'REFUSED');
const sizeOk = zs.length === 16 && zPass === 16 && fz.length === 6 && fPass === 5 && fRef.join() === 'Z22';
const ok2 = gatePass === 40 && realPass === 20 && sPass === 19 && sRef === 1 && sFail === 0 && sizeOk && regress.byteIdentical === regress.baselineFiles && regress.different.length === 0 && regress.missing.length === 0 && regress.extra.length === 0;
if (!ok2) missed.push(`2. regression: gate ${gatePass}/40, real-page ${realPass}/20, responsive ${sPass}/${sRef}/${sFail}, size ${zPass}/16 and flex ${fPass} PASS + ${fRef.join(',') || 'no'} REFUSED, byte-identical ${regress.byteIdentical}/${regress.baselineFiles}`);

// 3. round trips
const rt = (rows: Record<string, string>[], key: string, val: string) => rows.filter((r) => r[key] === val && r.rule === 'RT');
const rtOld = [...rt(gate, 'type', 'ROUNDTRIP'), ...rt(real, 'type', 'ROUNDTRIP'), ...rt(resp, 'kind', 'roundtrip'), ...rt(size, 'kind', 'roundtrip'), ...rt(flex, 'kind', 'roundtrip')];
const rtNew = ins.filter((r) => r.rule === 'RT');
const rtAll = [...rtOld, ...rtNew];
const ok3 = rtOld.length === 34 && rtNew.length === 10 && rtAll.every((r) => r.pass === 'true');
if (!ok3) missed.push(`3. no-op round trips: ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical (expected 34 existing + 10 new rows covering 11 files)`);

// 4. speed
const sp = [
  { n: 'preview ready, worst per-file median', v: timing.overall.worstMedian_previewMs, t: 100, u: 'ms' },
  { n: 'apply + export, worst per-file median', v: timing.overall.worstMedian_applyMs, t: 10, u: 'ms' },
  { n: 'bundle gzip', v: timing.bundle.gzipBytes, t: 102400, u: 'B' },
  { n: 'bundle raw', v: timing.bundle.rawBytes, t: 358400, u: 'B' },
  { n: '10x large page preview ready', v: timing.scaling['10x']!.previewMedianMs, t: 250, u: 'ms' },
  { n: '10x large page apply + export', v: timing.scaling['10x']!.applyMedianMs, t: 50, u: 'ms' },
];
const ok4 = sp.every((x) => x.v <= x.t);
if (!ok4) missed.push(`4. speed: ${sp.filter((x) => x.v > x.t).map((x) => `${x.n} ${x.v}${x.u} > ${x.t}${x.u}`).join('; ')}`);

// 5. unit tests, typecheck, lint, build
const vjson = join(ROOT, 'insert-check/tmp/vitest.json');
sh(`npx vitest run --reporter=json --outputFile=${vjson}`);
let total = 0, failed = 0, newTests = 0;
try {
  const j = JSON.parse(readFileSync(vjson, 'utf8')) as { numTotalTests: number; numFailedTests: number; testResults: { name: string; assertionResults: unknown[] }[] };
  total = j.numTotalTests; failed = j.numFailedTests;
  newTests = j.testResults.filter((f) => f.name.endsWith('structure.test.ts')).reduce((n, f) => n + f.assertionResults.length, 0);
} catch { failed = -1; }
const BASELINE = 151;
const tsc = sh('npx tsc --noEmit'), lint = sh('uv run ruff check . && uv run ruff format --check .'), build = sh('node harness/bundle.mjs');
const ok5 = failed === 0 && total >= BASELINE + newTests && newTests > 0 && tsc.ok && lint.ok && build.ok;
if (!ok5) missed.push(`5. tests ${total} (baseline ${BASELINE} + ${newTests} new), failed ${failed}; typecheck ${tsc.ok ? 'clean' : 'ERRORS'}, lint ${lint.ok ? 'clean' : 'ERRORS'}, build ${build.ok ? 'clean' : 'ERRORS'}`);

// 6. scorer check
const ok6 = /RESULT: all \d+ controls behaved/.test(scorer);
if (!ok6) missed.push('6. scorer check did not pass (insert-check/results/scorer-check.txt)');

// 7. locked files byte-identical
const lockedNow = sh('git diff --quiet f777429 HEAD -- docs/insert-comments-rules.md fixtures/insert').ok;
const lockedBefore = sh('git diff --quiet 27065d8 HEAD -- docs/gate-rules.md docs/realpage-rules.md docs/responsive-rules.md docs/responsive-rules-amendment-1.md docs/responsive-rules-amendment-2.md docs/size-scaling-rules.md docs/size-scaling-rules-amendment-1.md fixtures/edits.json fixtures/responsive fixtures/size fixtures/size-flex realpage-check/edits.json docs/speed-thresholds.md engine/test/css.test.ts engine/test/dom.test.ts engine/test/edit.test.ts engine/test/helpers.ts engine/test/markup.test.ts engine/test/model.test.ts engine/test/patch.test.ts engine/test/responsive.test.ts engine/test/specificity.test.ts').ok;
const ok7 = lockedNow && lockedBefore;
if (!ok7) missed.push(`7. locked files changed (insert lock ${lockedNow ? 'intact' : 'CHANGED'}, earlier locked files and existing tests ${lockedBefore ? 'intact' : 'CHANGED'})`);

// 8. one complete final run on the final commit
const head = sh('git rev-parse --short HEAD').out.trim();
const dirty = sh('git status --porcelain -- engine harness fixtures docs/insert-comments-rules.md').out.trim();
const ok8 = dirty === '';
if (!ok8) missed.push(`8. engine, harness or locked files have uncommitted changes: ${dirty.split('\n').join('; ')}`);

md.push('## Pass line', '', '| item | measured | line | met |', '|---|---|---|---|');
md.push(`| 1. the 36 I-specs | ${nPass} PASS, ${nRef} REFUSED as declared, ${nFail} FAIL | every spec meets its declared outcome, 0 FAIL | ${ok1 ? 'yes' : '**NO**'} |`);
md.push(`| 2. regression | gate ${gatePass}/40, real-page ${realPass}/20, responsive ${sPass} PASS / ${sRef} REFUSED / ${sFail} FAIL, size ${zPass}/16 PASS, flex ${fPass} PASS + ${fRef.join(',') || '-'} REFUSED, byte-identical ${regress.byteIdentical}/${regress.baselineFiles} | 40/40, 20/20, 19/1/0, 16 and 5+Z22, all identical | ${ok2 ? 'yes' : '**NO**'} |`);
md.push(`| 3. no-op round trips | ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} rows byte-identical (34 existing + ${rtNew.length} new rows covering 11 files) | all | ${ok3 ? 'yes' : '**NO**'} |`);
md.push(`| 4. speed thresholds | see below | all met | ${ok4 ? 'yes' : '**NO**'} |`);
md.push(`| 5. tests, typecheck, lint, build | ${total} tests pass (baseline ${BASELINE} + ${newTests} new), ${failed} fail; typecheck ${tsc.ok ? 'clean' : 'ERRORS'}; lint ${lint.ok ? 'clean' : 'ERRORS'}; build ${build.ok ? 'clean' : 'ERRORS'} | no fewer than baseline + new, 0 fail, clean | ${ok5 ? 'yes' : '**NO**'} |`);
md.push(`| 6. scorer check | ${ok6 ? 'passed' : 'NOT passed'} (\`scorer-check.txt\`) | passed | ${ok6 ? 'yes' : '**NO**'} |`);
md.push(`| 7. locked files | insert lock ${lockedNow ? 'byte-identical' : 'CHANGED'}; earlier locked files and existing unit tests ${lockedBefore ? 'unchanged' : 'CHANGED'} | byte-identical | ${ok7 ? 'yes' : '**NO**'} |`);
md.push(`| 8. one complete final run on the final commit | run ${RUN} at commit ${head}, no uncommitted engine/harness changes: ${ok8 ? 'yes' : 'NO'} | yes | ${ok8 ? 'yes' : '**NO**'} |`, '');
md.push('### Speed', '', '| metric | measured | threshold | met |', '|---|---|---|---|');
for (const x of sp) md.push(`| ${x.n} | ${x.v} ${x.u} | <= ${x.t} ${x.u} | ${x.v <= x.t ? 'yes' : '**NO**'} |`);
md.push('', '## Specs', '', '| id | fixture | outcome | failing checks / refusal |', '|---|---|---|---|');
for (const x of outs) {
  const rows = ins.filter((r) => r.id === x.id);
  const detail = x.o === 'REFUSED' ? (rows.find((r) => r.rule === 'R1')?.detail ?? '') : rows.filter((r) => r.pass === 'false').map((r) => `${r.rule}: ${(r.detail ?? '').slice(0, 120)}`).join(' | ') || rows.map((r) => r.rule).join(' ');
  md.push(`| ${x.id} | ${x.fixture} | ${x.o} | ${detail.replace(/\|/g, '/')} |`);
}
md.push('', '## Failures', '');
for (const x of outs.filter((y) => y.o === 'FAIL')) md.push(`- **${x.id}**: ${ins.filter((r) => r.id === x.id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500)}`);
for (const id of gateIds.filter((i) => !allPass(gate, 'edit_id', i))) md.push(`- **gate ${id}**`);
for (const id of realIds.filter((i) => !allPass(real, 'edit_id', i))) md.push(`- **real-page ${id}**`);
md.push('', `## Verdict, run ${RUN}: **${missed.length === 0 ? 'PASS' : 'FAIL'}**`, '');
for (const m of missed) md.push(`- ${m}`);
writeFileSync(join(ROOT, 'insert-check/results/insert-summary.md'), `${md.join('\n')}\n`);
console.log(md.slice(-8).join('\n'));
