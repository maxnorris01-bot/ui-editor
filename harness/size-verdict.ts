// Computes the size-scaling verdict ONLY from the pass line in docs/size-scaling-rules.md section 4.
// Writes size-check/results/size-summary.md.
//   GATE_RUN=<n> npx tsx harness/size-verdict.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

const RUN = process.env.GATE_RUN ?? 'size1';
function csv(path: string): Record<string, string>[] {
  const lines = readFileSync(path, 'utf8').split('\n').filter(Boolean);
  const head = lines[0]!.split(',');
  return lines.slice(1).map((line) => {
    const cells: string[] = []; let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) { const c = line[i]!; if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; } else if (c === '"') inQ = true; else if (c === ',') { cells.push(cur); cur = ''; } else cur += c; }
    cells.push(cur);
    return Object.fromEntries(head.map((h, i) => [h, cells[i] ?? '']));
  });
}
const size = csv(join(ROOT, 'size-check/results/size-results.csv')).filter((r) => r.run === RUN);
const resp = csv(join(ROOT, 'responsive-check/results/responsive-results.csv')).filter((r) => r.run === RUN);
const gate = csv(join(ROOT, 'results/gate-results.csv')).filter((r) => r.run === RUN);
const real = csv(join(ROOT, 'realpage-check/results/realpage-results.csv')).filter((r) => r.run === RUN);
const regress = JSON.parse(readFileSync(join(ROOT, 'size-check/results/regression.json'), 'utf8')) as { requiredIdentical: number; byteIdentical: number; notIdentical: string[]; listed: { id: string; identical: boolean }[] };
const timing = JSON.parse(readFileSync(join(ROOT, 'results/timing.json'), 'utf8')) as { bundle: { rawBytes: number; gzipBytes: number }; overall: { worstMedian_previewMs: number; worstMedian_applyMs: number }; scaling: Record<string, { previewMedianMs: number; applyMedianMs: number }> };
const scorer = readFileSync(join(ROOT, 'size-check/results/scorer-check.txt'), 'utf8').split('\n')[0]!.trim();

const outcome = (rows: Record<string, string>[], id: string, key = 'id') => rows.find((r) => r[key] === id)?.outcome ?? 'FAIL';
const idsOf = (rows: Record<string, string>[], key: string, pat: RegExp) => [...new Set(rows.filter((r) => pat.test(r[key] ?? '') && r.kind !== 'roundtrip').map((r) => r[key] ?? ''))];
const md: string[] = [`# Size scaling results, run ${RUN}`, '', 'Generated by `harness/size-verdict.ts` from the result files. Do not edit by hand. The truth of each REFUSED reason is checked separately by reading the file (session note).', ''];
const missed: string[] = [];

// 1. the 16 specs
const zs = idsOf(size, 'id', /^Z\d+$/);
const zOut = zs.map((id) => ({ id, o: outcome(size, id) }));
const zPass = zOut.filter((x) => x.o === 'PASS').length, zFail = zOut.filter((x) => x.o === 'FAIL').length;
const ok1 = zs.length === 16 && zPass >= 15 && zFail === 0;
if (!ok1) missed.push(`1. size specs: ${zPass} PASS, ${zFail} FAIL of ${zs.length} (line: >= 15 PASS, 0 FAIL)`);

// 2. regression
const gateIds = [...new Set(gate.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const allPass = (rows: Record<string, string>[], key: string, id: string) => rows.filter((r) => r[key] === id && ['E1', 'E2', 'E3', 'E4', 'E5'].includes(r.rule ?? '')).every((r) => r.pass === 'true');
const gatePass = gateIds.filter((id) => allPass(gate, 'edit_id', id)).length;
const realIds = [...new Set(real.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const realPass = realIds.filter((id) => allPass(real, 'edit_id', id)).length;
const sIds = idsOf(resp, 'id', /^S\d+$/);
const sOut = sIds.map((id) => outcome(resp, id));
const sPass = sOut.filter((o) => o === 'PASS').length, sRef = sOut.filter((o) => o === 'REFUSED').length, sFail = sOut.filter((o) => o === 'FAIL').length;
const failedGate = gateIds.filter((id) => !allPass(gate, 'edit_id', id));
const ok2 = gatePass === 40 && realPass === 20 && sPass === 19 && sRef === 1 && sFail === 0 && regress.byteIdentical === regress.requiredIdentical && regress.notIdentical.length === 0;
if (!ok2) missed.push(`2. regression: gate ${gatePass}/40${failedGate.length ? ` (failed: ${failedGate.join(', ')})` : ''}, real-page ${realPass}/20, responsive ${sPass} PASS / ${sRef} REFUSED / ${sFail} FAIL, byte-identical ${regress.byteIdentical}/${regress.requiredIdentical}`);

// 3. round trips
const rt = (rows: Record<string, string>[], key: string, val: string) => rows.filter((r) => r[key] === val && r.rule === 'RT');
const rtAll = [...rt(gate, 'type', 'ROUNDTRIP'), ...rt(real, 'type', 'ROUNDTRIP'), ...rt(resp, 'kind', 'roundtrip'), ...rt(size, 'kind', 'roundtrip')];
const ok3 = rtAll.length > 0 && rtAll.every((r) => r.pass === 'true');
if (!ok3) missed.push(`3. no-op round trips: ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical`);

// 4. speed
const sp = [
  { n: 'preview ready, worst per-file median', v: timing.overall.worstMedian_previewMs, t: 100, u: 'ms' },
  { n: 'apply + export, worst per-file median', v: timing.overall.worstMedian_applyMs, t: 10, u: 'ms' },
  { n: 'bundle gzip', v: timing.bundle.gzipBytes, t: 102400, u: 'B' },
  { n: 'bundle raw', v: timing.bundle.rawBytes, t: 358400, u: 'B' },
  { n: '10x large page preview ready', v: timing.scaling['10x']!.previewMedianMs, t: 250, u: 'ms' },
  { n: '10x large page apply + export', v: timing.scaling['10x']!.applyMedianMs, t: 50, u: 'ms' },
];
const ok4 = sp.every((x) => x.v <= x.t);
if (!ok4) missed.push(`4. speed: ${sp.filter((x) => x.v > x.t).map((x) => `${x.n} ${x.v}${x.u} > ${x.t}${x.u}`).join('; ')}`);
const ok5 = scorer === 'PASS';
if (!ok5) missed.push('5. scorer check did not pass');

// listed width/height edits still pass
const listed = [
  ...['E02', 'E10', 'E14', 'E18'].map((id) => ({ id, ok: allPass(gate, 'edit_id', id) })),
  ...['R02', 'R06', 'R14', 'R18'].map((id) => ({ id, ok: allPass(real, 'edit_id', id) })),
  { id: 'S18', ok: outcome(resp, 'S18') === 'PASS' },
];

md.push('## Pass line', '', '| item | measured | line | met |', '|---|---|---|---|');
md.push(`| 1. size specs | ${zPass} PASS, ${zOut.filter((x) => x.o === 'REFUSED').length} REFUSED, ${zFail} FAIL of ${zs.length} | >= 15 PASS and 0 FAIL | ${ok1 ? 'yes' : '**NO**'} |`);
md.push(`| 2. regression | gate ${gatePass}/40, real-page ${realPass}/20, responsive ${sPass} PASS / ${sRef} REFUSED / ${sFail} FAIL, byte-identical ${regress.byteIdentical}/${regress.requiredIdentical} | 40/40, 20/20, 19/1/0, all identical | ${ok2 ? 'yes' : '**NO**'} |`);
md.push(`| 3. no-op round trips | ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical | all | ${ok3 ? 'yes' : '**NO**'} |`);
md.push(`| 4. speed thresholds | see below | all met | ${ok4 ? 'yes' : '**NO**'} |`);
md.push(`| 5. scorer check | ${scorer} (\`scorer-check.txt\`) | passed | ${ok5 ? 'yes' : '**NO**'} |`, '');
md.push('### Width/height edits that were allowed to change bytes', '', '| edit | still PASS E1 to E5 | export changed |', '|---|---|---|');
for (const l of listed) md.push(`| ${l.id} | ${l.ok ? 'yes' : '**NO**'} | ${regress.listed.find((x) => x.id.endsWith(`/${l.id}`))?.identical ? 'no (identical)' : 'yes'} |`);
md.push('', '### Speed', '', '| metric | measured | threshold | met |', '|---|---|---|---|');
for (const x of sp) md.push(`| ${x.n} | ${x.v} ${x.u} | <= ${x.t} ${x.u} | ${x.v <= x.t ? 'yes' : '**NO**'} |`);
md.push('', '## Specs (outcome, diff size, notes)', '', '| id | case | fixture | outcome | diff | notes |', '|---|---|---|---|---|---|');
for (const id of zs) {
  const r = size.filter((x) => x.id === id);
  const e5 = r.find((x) => x.rule === 'E5')?.detail ?? '';
  const notes = JSON.parse(r.find((x) => x.rule === 'NOTES')?.detail || '[]') as unknown[];
  md.push(`| ${id} | ${r[0]!.case} | ${r[0]!.fixture} | ${outcome(size, id)} | ${e5.split(' | ')[0]} | ${notes.length} |`);
}
md.push('', '## Failures', '');
for (const x of zOut.filter((y) => y.o === 'FAIL')) md.push(`- **${x.id}**: ${size.filter((r) => r.id === x.id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500)}`);
for (const id of failedGate) md.push(`- **gate ${id}**: ${gate.filter((r) => r.edit_id === id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500)}`);
for (const id of realIds.filter((i) => !allPass(real, 'edit_id', i))) md.push(`- **real-page ${id}**: ${real.filter((r) => r.edit_id === id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500)}`);
md.push('', '## Refusals', '');
for (const x of zOut.filter((y) => y.o === 'REFUSED')) md.push(`- **${x.id}**: ${size.find((r) => r.id === x.id && r.rule === 'E2')?.detail}`);
md.push('', `## Verdict, run ${RUN}: **${missed.length === 0 ? 'PASS' : 'FAIL'}**`, '');
for (const m of missed) md.push(`- ${m}`);
writeFileSync(join(ROOT, 'size-check/results/size-summary.md'), `${md.join('\n')}\n`);
console.log(md.slice(-6).join('\n'));
