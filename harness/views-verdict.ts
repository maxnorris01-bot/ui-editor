// Computes the small-views verdict ONLY from the pass line in docs/small-views-rules.md section 6 (with amendment 1).
// Writes views-check/results/views-summary.md.
//   GATE_RUN=<id> npx tsx harness/views-verdict.ts
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

const RUN = process.env.GATE_RUN ?? 'm1';
function csv(path: string): Record<string, string>[] {
  const lines = readFileSync(path, 'utf8').split('\n').filter(Boolean);
  const head = lines[0]!.split(',');
  return lines.slice(1).map((line) => {
    const cells: string[] = []; let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) { const c = line[i]!; if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; } else if (c === '"') inQ = true; else if (c === ',') { cells.push(cur); cur = ''; } else cur += c; }
    cells.push(cur);
    return Object.fromEntries(head.map((h, i) => [h, cells[i] ?? '']));
  });
}
const sh = (cmd: string): { ok: boolean; out: string } => { try { return { ok: true, out: execSync(cmd, { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] }).toString() }; } catch (e) { return { ok: false, out: String((e as { stdout?: Buffer }).stdout ?? e) }; } };

const ins = csv(join(ROOT, 'insert-check/results/insert-results.csv')).filter((r) => r.run === RUN);
const har = csv(join(ROOT, 'harden-check/results/harden-results.csv')).filter((r) => r.run === RUN);
const vws = csv(join(ROOT, 'views-check/results/views-results.csv')).filter((r) => r.run === RUN);
const size = csv(join(ROOT, 'size-check/results/size-results.csv')).filter((r) => r.run === RUN);
const flex = csv(join(ROOT, 'size-check/results/size-flex-results.csv')).filter((r) => r.run === RUN);
const resp = csv(join(ROOT, 'responsive-check/results/responsive-results.csv')).filter((r) => r.run === RUN);
const gate = csv(join(ROOT, 'results/gate-results.csv')).filter((r) => r.run === RUN);
const real = csv(join(ROOT, 'realpage-check/results/realpage-results.csv')).filter((r) => r.run === RUN);
const regress = JSON.parse(readFileSync(join(ROOT, 'views-check/results/regression.json'), 'utf8')) as { baselineFiles: number; comparedFiles: number; byteIdentical: number; different: string[]; missing: string[]; extra: string[] };
const timing = JSON.parse(readFileSync(join(ROOT, 'results/timing.json'), 'utf8')) as { bundle: { rawBytes: number; gzipBytes: number }; overall: { worstMedian_previewMs: number; worstMedian_applyMs: number }; scaling: Record<string, { previewMedianMs: number; applyMedianMs: number }> };
const scorer = readFileSync(join(ROOT, 'views-check/results/scorer-check.txt'), 'utf8');

const outcome = (rows: Record<string, string>[], id: string) => rows.find((r) => r.id === id)?.outcome ?? 'FAIL';
const idsOf = (rows: Record<string, string>[], key: string, pat: RegExp) => [...new Set(rows.filter((r) => pat.test(r[key] ?? '') && r.kind !== 'roundtrip').map((r) => r[key] ?? ''))];
const missed: string[] = [];
const md: string[] = [`# Small views, results of run ${RUN}`, '', 'Generated by `harness/insert-verdict.ts` from the result files. Do not edit by hand. The truth of each REFUSED reason is checked separately: `harness/validate-views-specs.ts` reads the fixtures without the engine, and the session note quotes the reasons.', ''];

// 1. the 32 M-specs
const ids = [...new Set(vws.filter((r) => /^M\d+$/.test(r.id ?? '')).map((r) => r.id!))];
const outs = ids.map((id) => ({ id, o: outcome(vws, id), fixture: vws.find((r) => r.id === id)!.fixture }));
const nPass = outs.filter((x) => x.o === 'PASS').length, nRef = outs.filter((x) => x.o === 'REFUSED').length, nFail = outs.filter((x) => x.o === 'FAIL').length;
const ok1 = ids.length === 32 && nFail === 0 && nRef === 1 && outs.find((x) => x.o === 'REFUSED')?.id === 'M20';
if (!ok1) missed.push(`1. M-specs: ${nPass} PASS, ${nRef} REFUSED, ${nFail} FAIL of ${ids.length} (line: 32 specs, 0 FAIL, the only REFUSED is M20)`);
const hIds = [...new Set(har.filter((r) => /^H\d+$/.test(r.id ?? '')).map((r) => r.id!))];
const hPass = hIds.filter((id) => outcome(har, id) === 'PASS').length;
const iIds = [...new Set(ins.filter((r) => /^I\d+$/.test(r.id ?? '')).map((r) => r.id!))];
const iOut = iIds.map((id) => outcome(ins, id));
const iPass = iOut.filter((o) => o === 'PASS').length, iRef = iOut.filter((o) => o === 'REFUSED').length, iFail = iOut.filter((o) => o === 'FAIL').length;

// 2. regression
const gateIds = [...new Set(gate.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const allPass = (rows: Record<string, string>[], key: string, id: string) => rows.filter((r) => r[key] === id && ['E1', 'E2', 'E3', 'E4', 'E5'].includes(r.rule ?? '')).every((r) => r.pass === 'true');
const gatePass = gateIds.filter((id) => allPass(gate, 'edit_id', id)).length;
const realIds = [...new Set(real.filter((r) => r.type !== 'ROUNDTRIP').map((r) => r.edit_id ?? ''))];
const realPass = realIds.filter((id) => allPass(real, 'edit_id', id)).length;
const sIds = idsOf(resp, 'id', /^S\d+$/);
const sOut = sIds.map((id) => outcome(resp, id));
const sKept = sIds.filter((id) => id !== 'S09').map((id) => outcome(resp, id));
const sPass = sKept.filter((o) => o === 'PASS').length, sRef = sKept.filter((o) => o === 'REFUSED').length, sFail = sKept.filter((o) => o === 'FAIL').length;
const zs = idsOf(size, 'id', /^Z\d+$/), fz = idsOf(flex, 'id', /^Z\d+$/);
const zPass = zs.filter((id) => id !== 'Z09' && outcome(size, id) === 'PASS').length;
const fPass = fz.filter((id) => outcome(flex, id) === 'PASS').length, fRef = fz.filter((id) => outcome(flex, id) === 'REFUSED');
const sizeOk = zs.length === 16 && zPass === 15 && fz.length === 6 && fPass === 5 && fRef.join() === 'Z22';
const ok2 = iIds.length === 36 && iPass === 30 && iRef === 6 && iFail === 0 && gatePass === 40 && realPass === 20 && sPass === 18 && sRef === 1 && sFail === 0 && hIds.length === 20 && hPass === 20 && sizeOk && regress.byteIdentical === regress.comparedFiles && regress.different.length === 0 && regress.missing.length === 0 && regress.extra.length === 0;
if (!ok2) missed.push(`2. regression: insert ${iPass}/${iRef}/${iFail}, gate ${gatePass}/40, real-page ${realPass}/20, responsive ${sPass}/${sRef}/${sFail}, size ${zPass}/16 and flex ${fPass} PASS + ${fRef.join(',') || 'no'} REFUSED, byte-identical ${regress.byteIdentical}/${regress.baselineFiles}`);

// 3. round trips
const rt = (rows: Record<string, string>[], key: string, val: string) => rows.filter((r) => r[key] === val && r.rule === 'RT');
const rtOld = [...rt(gate, 'type', 'ROUNDTRIP'), ...rt(real, 'type', 'ROUNDTRIP'), ...rt(resp, 'kind', 'roundtrip'), ...rt(size, 'kind', 'roundtrip'), ...rt(flex, 'kind', 'roundtrip')];
const rtNew = ins.filter((r) => r.rule === 'RT');
const rtHard = har.filter((r) => r.rule === 'RT');
const rtViews = vws.filter((r) => r.rule === 'RT');
const rtAll = [...rtOld, ...rtNew, ...rtHard, ...rtViews];
const ok3 = rtOld.length === 34 && rtNew.length === 10 && rtHard.length === 10 && rtViews.length === 14 && rtAll.every((r) => r.pass === 'true');
if (!ok3) missed.push(`3. no-op round trips: ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} byte-identical (expected 34 existing + 10 insert + 10 hardening + 14 views fixtures)`);

// 4. speed
const sp = [
  { n: 'preview ready, worst per-file median', v: timing.overall.worstMedian_previewMs, t: 100, u: 'ms' },
  { n: 'apply + export, worst per-file median', v: timing.overall.worstMedian_applyMs, t: 10, u: 'ms' },
  { n: 'bundle gzip', v: timing.bundle.gzipBytes, t: 102400, u: 'B' },
  { n: 'bundle raw', v: timing.bundle.rawBytes, t: 358400, u: 'B' },
  { n: '10x large page preview ready', v: timing.scaling['10x']!.previewMedianMs, t: 250, u: 'ms' },
  { n: '10x large page apply + export', v: timing.scaling['10x']!.applyMedianMs, t: 50, u: 'ms' },
];
const ok4 = sp.every((x) => x.v <= x.t);
if (!ok4) missed.push(`4. speed: ${sp.filter((x) => x.v > x.t).map((x) => `${x.n} ${x.v}${x.u} > ${x.t}${x.u}`).join('; ')}`);

// 5. unit tests, typecheck, lint, build
const vjson = join(ROOT, 'insert-check/tmp/vitest.json');
sh(`npx vitest run --reporter=json --outputFile=${vjson}`);
let total = 0, failed = 0, newTests = 0;
try {
  const j = JSON.parse(readFileSync(vjson, 'utf8')) as { numTotalTests: number; numFailedTests: number; testResults: { name: string; assertionResults: unknown[] }[] };
  total = (j as unknown as { numPassedTests: number }).numPassedTests; failed = j.numFailedTests;
  newTests = j.testResults.filter((f) => f.name.endsWith('views.test.ts')).reduce((n, f) => n + f.assertionResults.length, 0);
} catch { failed = -1; }
const BASELINE = 204;
const tsc = sh('npx tsc --noEmit'), lint = sh('uv run ruff check . && uv run ruff format --check .'), build = sh('node harness/bundle.mjs');
const ok5 = failed === 0 && total >= BASELINE + newTests && newTests > 0 && tsc.ok && lint.ok && build.ok;
if (!ok5) missed.push(`5. tests ${total} (baseline ${BASELINE} + ${newTests} new), failed ${failed}; typecheck ${tsc.ok ? 'clean' : 'ERRORS'}, lint ${lint.ok ? 'clean' : 'ERRORS'}, build ${build.ok ? 'clean' : 'ERRORS'}`);

// 6. scorer check
const ok6 = /RESULT: all \d+ controls behaved/.test(scorer);
if (!ok6) missed.push('6. scorer check did not pass (views-check/results/scorer-check.txt)');

// 7. locked files byte-identical
const lockedNow = sh('git diff --quiet 647ff3b HEAD -- docs/small-views-rules.md fixtures/views').ok && sh('git diff --quiet f6303d1 HEAD -- docs/small-views-rules-amendment-1.md').ok;
const lockedBefore = sh('git diff --quiet a5f954a HEAD -- docs/gate-rules.md docs/realpage-rules.md docs/responsive-rules.md docs/responsive-rules-amendment-1.md docs/responsive-rules-amendment-2.md docs/size-scaling-rules.md docs/size-scaling-rules-amendment-1.md docs/insert-comments-rules.md docs/insert-comments-rules-amendment-1.md docs/hardening-rules.md docs/hardening-rules-amendment-1.md fixtures/edits.json fixtures/responsive fixtures/size fixtures/size-flex fixtures/insert fixtures/harden realpage-check/edits.json docs/speed-thresholds.md engine/test/css.test.ts engine/test/dom.test.ts engine/test/edit.test.ts engine/test/helpers.ts engine/test/markup.test.ts engine/test/model.test.ts engine/test/patch.test.ts engine/test/specificity.test.ts engine/test/structure.test.ts engine/test/hardening.test.ts').ok;
// the one existing unit test that is RETIRED (rules section 5): only a comment line and `it` becoming `it.skip`
const rtDiff = sh('git diff -U0 a5f954a HEAD -- engine/test/responsive.test.ts').out.split('\n').filter((l) => /^[+-][^+-]/.test(l));
const rtOk = rtDiff.length === 3 && rtDiff.some((l) => l.includes('it.skip(')) && rtDiff.some((l) => l.includes('RETIRED'));
const ok7 = lockedNow && lockedBefore && rtOk;
if (!ok7) missed.push(`7. locked files changed (views lock ${lockedNow ? 'intact' : 'CHANGED'}, earlier locked files and existing tests ${lockedBefore ? 'intact' : 'CHANGED'}, the retired unit test ${rtOk ? 'only retired' : 'CHANGED BEYOND THE RETIREMENT'})`);

// 8. one complete final run on the final commit
const head = sh('git rev-parse --short HEAD').out.trim();
const dirty = sh('git status --porcelain -- engine harness fixtures docs/small-views-rules.md').out.trim();
const ok8 = dirty === '';
if (!ok8) missed.push(`8. engine, harness or locked files have uncommitted changes: ${dirty.split('\n').join('; ')}`);

md.push('## Pass line', '', '| item | measured | line | met |', '|---|---|---|---|');
md.push(`| 1. the 32 M-specs | ${nPass} PASS, ${nRef} REFUSED (M20), ${nFail} FAIL | every spec meets its declared outcome, 0 FAIL | ${ok1 ? 'yes' : '**NO**'} |`);
md.push(`| 2. regression | insert specs ${iPass} PASS + ${iRef} REFUSED + ${iFail} FAIL, gate ${gatePass}/40, real-page ${realPass}/20, responsive ${sPass} PASS / ${sRef} REFUSED / ${sFail} FAIL, size ${zPass}/16 PASS, flex ${fPass} PASS + ${fRef.join(',') || '-'} REFUSED, byte-identical ${regress.byteIdentical}/${regress.baselineFiles} | 30+6+0, 40/40, 20/20, 19/1/0, 16 and 5+Z22, all identical | ${ok2 ? 'yes' : '**NO**'} |`);
md.push(`| 3. no-op round trips | ${rtAll.filter((r) => r.pass === 'true').length} of ${rtAll.length} rows byte-identical (34 existing + ${rtNew.length} insert + ${rtHard.length} hardening + ${rtViews.length} views) | all | ${ok3 ? 'yes' : '**NO**'} |`);
md.push(`| 4. speed thresholds | see below | all met | ${ok4 ? 'yes' : '**NO**'} |`);
md.push(`| 5. tests, typecheck, lint, build | ${total} tests pass (baseline ${BASELINE} + ${newTests} new), ${failed} fail; typecheck ${tsc.ok ? 'clean' : 'ERRORS'}; lint ${lint.ok ? 'clean' : 'ERRORS'}; build ${build.ok ? 'clean' : 'ERRORS'} | no fewer than baseline + new, 0 fail, clean | ${ok5 ? 'yes' : '**NO**'} |`);
md.push(`| 6. scorer check | ${ok6 ? 'passed' : 'NOT passed'} (\`scorer-check.txt\`) | passed | ${ok6 ? 'yes' : '**NO**'} |`);
md.push(`| 7. locked files | views lock ${lockedNow ? 'byte-identical' : 'CHANGED'}; earlier locked files and existing unit tests ${lockedBefore ? 'unchanged' : 'CHANGED'}; the RETIRED unit test ${rtOk ? 'only skipped with a comment' : 'CHANGED BEYOND THAT'} | byte-identical | ${ok7 ? 'yes' : '**NO**'} |`);
md.push(`| 8. one complete final run on the final commit | run ${RUN} at commit ${head}, no uncommitted engine/harness changes: ${ok8 ? 'yes' : 'NO'} | yes | ${ok8 ? 'yes' : '**NO**'} |`, '');
md.push('### Speed', '', '| metric | measured | threshold | met |', '|---|---|---|---|');
for (const x of sp) md.push(`| ${x.n} | ${x.v} ${x.u} | <= ${x.t} ${x.u} | ${x.v <= x.t ? 'yes' : '**NO**'} |`);
md.push('', '## Specs', '', '| id | fixture | outcome | checks run / failing |', '|---|---|---|---|');
for (const x of outs) {
  const rows = vws.filter((r) => r.id === x.id);
  const detail = rows.filter((r) => r.pass === 'false').map((r) => `${r.rule}: ${(r.detail ?? '').slice(0, 120)}`).join(' | ') || rows.map((r) => r.rule).join(' ');
  md.push(`| ${x.id} | ${x.fixture} | ${x.o} | ${detail.replace(/\|/g, '/')} |`);
}
md.push('', '## Failures', '');
for (const x of outs.filter((y) => y.o === 'FAIL')) md.push(`- **${x.id}**: ${vws.filter((r) => r.id === x.id && r.pass === 'false').map((r) => `${r.rule}: ${r.detail}`).join(' || ').slice(0, 500)}`);
for (const id of gateIds.filter((i) => !allPass(gate, 'edit_id', i))) md.push(`- **gate ${id}**`);
for (const id of realIds.filter((i) => !allPass(real, 'edit_id', i))) md.push(`- **real-page ${id}**`);
md.push('', `## Verdict, run ${RUN}: **${missed.length === 0 ? 'PASS' : 'FAIL'}**`, '');
for (const m of missed) md.push(`- ${m}`);
writeFileSync(join(ROOT, 'views-check/results/views-summary.md'), `${md.join('\n')}\n`);
console.log(md.slice(-8).join('\n'));
