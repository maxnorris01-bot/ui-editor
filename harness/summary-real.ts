// Builds realpage-check/results/realpage-summary.md from realpage-results.csv (and timing.json).
// Pass line (docs/realpage-rules.md section 3): >= 16 of 20 PASS, zero FAIL, all no-op round trips byte-identical.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './fixtures';

interface Row { run: string; edit_id: string; file: string; type: string; rule: string; outcome: string; pass: boolean; detail: string }
function parseCsv(text: string): Row[] {
  return text.split('\n').filter(Boolean).slice(1).map((line) => {
    const cells: string[] = [];
    let cur = '', inQ = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i]!;
      if (inQ) { if (c === '"') { if (line[i + 1] === '"') { cur += '"'; i++; } else inQ = false; } else cur += c; }
      else if (c === '"') inQ = true;
      else if (c === ',') { cells.push(cur); cur = ''; }
      else cur += c;
    }
    cells.push(cur);
    return { run: cells[0]!, edit_id: cells[1]!, file: cells[2]!, type: cells[3]!, rule: cells[4]!, outcome: cells[5]!, pass: cells[6] === 'true', detail: cells[7] ?? '' };
  });
}

export function writeRealSummary(): void {
  const dir = join(ROOT, 'realpage-check/results');
  const all = parseCsv(readFileSync(join(dir, 'realpage-results.csv'), 'utf8'));
  const spec = JSON.parse(readFileSync(join(ROOT, 'realpage-check/edits.json'), 'utf8')) as { edits: { id: string; file: string; type: string; target: string }[] };
  const md: string[] = ['# Real-page check results', '', 'Generated by `harness/summary-real.ts` from `realpage-results.csv`. Do not edit by hand. The truth of each REFUSED reason is checked separately by reading the file (see the session note).', ''];
  for (const run of [...new Set(all.map((r) => r.run))]) {
    const rr = all.filter((r) => r.run === run);
    const edits = spec.edits;
    const outcome = (id: string) => rr.find((r) => r.edit_id === id)?.outcome ?? 'FAIL';
    const counts = { PASS: 0, REFUSED: 0, FAIL: 0 } as Record<string, number>;
    for (const e of edits) counts[outcome(e.id)] = (counts[outcome(e.id)] ?? 0) + 1;
    const rt = rr.filter((r) => r.type === 'ROUNDTRIP' && r.rule === 'RT');
    const rtOk = rt.length > 0 && rt.every((r) => r.pass);
    const rtFiles = new Set(rt.filter((r) => r.pass).map((r) => r.file));
    const e1rt = rr.filter((r) => r.type === 'ROUNDTRIP' && r.rule === 'E1');
    md.push(`## Run ${run}`, '', '### Pass line', '', '| item | measured | line | met |', '|---|---|---|---|');
    md.push(`| PASS | ${counts.PASS} of ${edits.length} | >= 16 | ${counts.PASS! >= 16 ? 'yes' : '**NO**'} |`);
    md.push(`| FAIL | ${counts.FAIL} | 0 | ${counts.FAIL === 0 ? 'yes' : '**NO**'} |`);
    md.push(`| REFUSED | ${counts.REFUSED} | (allowed if true) | n/a |`);
    md.push(`| no-op round trips byte-identical (files incl. companion CSS) | ${rt.filter((r) => r.pass).length} of ${rt.length} | all | ${rtOk ? 'yes' : '**NO**'} |`, '');
    md.push('### Per file', '');
    for (const file of [...new Set(edits.map((e) => e.file))]) {
      md.push(`**${file}** (no-op round trip: ${rt.filter((r) => r.file === file || r.file.endsWith('.css') && file.startsWith('freelancer')).every((r) => r.pass) ? 'byte-identical' : '**FAIL**'}; no-op load: ${e1rt.filter((r) => r.file === file).every((r) => r.pass) ? 'ok' : '**FAIL**'})`, '', '| edit | type | target | outcome | diff size / reason |', '|---|---|---|---|---|');
      for (const e of edits.filter((x) => x.file === file)) {
        const e5 = rr.find((r) => r.edit_id === e.id && r.rule === 'E5');
        const bad = rr.filter((r) => r.edit_id === e.id && !r.pass).map((r) => `${r.rule}: ${r.detail}`);
        const note = outcome(e.id) === 'PASS' ? (e5?.detail.replace(/^diff=/, '') ?? '') : bad.join(' || ').slice(0, 300);
        md.push(`| ${e.id} | ${e.type} | \`${e.target.replace(/\|/g, '\\|')}\` | ${outcome(e.id)} | ${note.replace(/\|/g, '/')} |`);
      }
      md.push('');
    }
    const refused = edits.filter((e) => outcome(e.id) === 'REFUSED');
    md.push(`### Refusals (${refused.length})`, '');
    for (const e of refused) md.push(`- **${e.id}** ${e.file} ${e.type}: ${rr.find((r) => r.edit_id === e.id && r.rule === 'E2')?.detail}`);
    const failed = edits.filter((e) => outcome(e.id) === 'FAIL');
    md.push('', `### Failures (${failed.length})`, '');
    for (const e of failed) md.push(`- **${e.id}** ${e.file} ${e.type}: ${rr.filter((r) => r.edit_id === e.id && !r.pass).map((r) => `${r.rule} (${r.detail})`).join('; ').slice(0, 700)}`);
    void rtFiles;
    const missed: string[] = [];
    if (counts.PASS! < 16) missed.push(`PASS ${counts.PASS} of ${edits.length} (line 16)`);
    if (counts.FAIL! > 0) missed.push(`FAIL ${counts.FAIL} (line 0)`);
    if (!rtOk) missed.push('no-op round trip not byte-identical for every file');
    md.push('', `### Verdict, run ${run}: **${missed.length === 0 ? 'PASS' : 'FAIL'}** (refusal reasons still need the read-the-file check)`, '');
    for (const m of missed) md.push(`- ${m}`);
    md.push('');
  }
  writeFileSync(join(dir, 'realpage-summary.md'), md.join('\n'));
}
